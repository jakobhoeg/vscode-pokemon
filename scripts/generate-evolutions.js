// Regenerates src/common/evolution-data.ts from PokéAPI species data.
// Usage: npm run compile:extension && node scripts/generate-evolutions.js
// Re-run whenever sprites are added to pokemon-data.ts.
const fs = require('fs');
const path = require('path');
const { POKEMON_DATA } = require('../out/common/pokemon-data.js');

const CSV_URL =
  'https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species.csv';
const OUT_FILE = path.join(__dirname, '../src/common/evolution-data.ts');

// Variant keys that exist here but can't evolve in the games.
const CANNOT_EVOLVE = new Set(['combee_male', 'pichu_spiky_eared']);

// Picks which variant key(s) of the target species a source key becomes:
// same suffix (burmy_sandy -> wormadam_sandy), else the plain key
// (onix -> steelix, not steelix_female), else every variant (wynaut -> wobbuffet_male/_female).
function resolveTargets(sourceKey, candidates) {
  if (candidates.length === 1) {
    return candidates;
  }
  const suffix = sourceKey.includes('_')
    ? sourceKey.slice(sourceKey.indexOf('_'))
    : '';
  const sameSuffix = suffix && candidates.find((c) => c.endsWith(suffix));
  if (sameSuffix) {
    return [sameSuffix];
  }
  const plain = candidates.find((c) =>
    candidates.every((other) => other === c || other.startsWith(`${c}_`)),
  );
  return plain ? [plain] : candidates;
}

async function main() {
  const response = await fetch(CSV_URL);
  if (!response.ok) {
    throw new Error(`Download failed: ${response.status} ${CSV_URL}`);
  }
  const rows = (await response.text()).trim().split('\n').slice(1);

  const evolvesInto = new Map(); // dex number -> dex numbers it evolves into
  for (const row of rows) {
    const [id, , , evolvesFrom] = row.split(',');
    if (evolvesFrom) {
      const from = Number(evolvesFrom);
      evolvesInto.set(from, [...(evolvesInto.get(from) ?? []), Number(id)]);
    }
  }

  const keysById = new Map(); // dex number -> keys that have sprites
  for (const [key, config] of Object.entries(POKEMON_DATA)) {
    keysById.set(config.id, [...(keysById.get(config.id) ?? []), key]);
  }

  const evolutions = {};
  for (const [key, config] of Object.entries(POKEMON_DATA)) {
    if (CANNOT_EVOLVE.has(key)) {
      continue;
    }
    const targets = (evolvesInto.get(config.id) ?? [])
      .filter((id) => keysById.has(id)) // drop forms we have no sprites for
      .flatMap((id) => resolveTargets(key, keysById.get(id)));
    if (targets.length > 0) {
      evolutions[key] = targets;
    }
  }

  const body = Object.entries(evolutions)
    .map(([key, targets]) => `  ${key}: ${JSON.stringify(targets)},`)
    .join('\n');
  fs.writeFileSync(
    OUT_FILE,
    `// Generated by scripts/generate-evolutions.js from PokéAPI. Do not edit by hand.
/* eslint-disable @typescript-eslint/naming-convention */
import { PokemonType } from './types';

export const EVOLUTION_DATA: Readonly<Record<string, PokemonType[]>> = {
${body}
};
`,
  );
  console.log(
    `Wrote ${Object.keys(evolutions).length} evolving pokemon to ${OUT_FILE}`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
